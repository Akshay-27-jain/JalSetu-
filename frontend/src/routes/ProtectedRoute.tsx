import React from 'react';
import { Navigate, Outlet } from 'react-router-dom';
import { useAuth } from '../context/AuthContext';
import type { Role } from '../types';

interface ProtectedRouteProps {
  allowedRoles?: Role[];
}

export const ProtectedRoute: React.FC<ProtectedRouteProps> = ({ allowedRoles }) => {
  const { isAuthenticated, isLoading, user } = useAuth();

  if (isLoading) {
    return (
      <div className="flex h-screen w-screen items-center justify-center bg-slate-50">
        <div className="flex flex-col items-center gap-3">
          <div className="h-9 w-9 animate-spin rounded-full border-3 border-brand-600 border-t-transparent" />
          <p className="text-sm font-semibold text-slate-500">Loading JalSetu...</p>
        </div>
      </div>
    );
  }

  if (!isAuthenticated || !user) {
    return <Navigate to="/login" replace />;
  }

  if (allowedRoles && !allowedRoles.includes(user.role)) {
    // Redirect to proper role dashboard
    if (user.role === 'MAIN_ADMIN') return <Navigate to="/main-admin/dashboard" replace />;
    if (user.role === 'COMMUNITY_ADMIN') return <Navigate to="/community-admin/dashboard" replace />;
    return <Navigate to="/resident/dashboard" replace />;
  }

  return <Outlet />;
};
